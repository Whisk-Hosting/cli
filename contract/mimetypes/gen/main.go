// Command gen writes types_gen.go from mime-db's db.json (https://github.com/jshttp/mime-db,
// MIT): each file extension's type, choosing as the mime-types package does when two types claim
// one extension, and whether each type compresses where mime-db says. update.sh runs it on the pinned
// release.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

type entry struct {
	Source       string   `json:"source"`
	Compressible *bool    `json:"compressible"`
	Extensions   []string `json:"extensions"`
}

// score is how much a source is trusted when two types claim one extension: IANA's register
// first, then a type no list names, then Apache's, then nginx's.
func score(source string) int {
	switch source {
	case "iana":
		return 4
	case "":
		return 3
	case "apache":
		return 2
	case "nginx":
		return 1
	}
	return 0
}

// better is whether type t from source should take an extension from was: a more trusted source
// wins, and between equals a type outside application/ (video/mp4 over application/mp4), as the
// mime-score rules the mime-types package follows. application/octet-stream never wins.
func better(t, source, was, wasSource string) bool {
	switch {
	case was == "application/octet-stream":
		return true
	case t == "application/octet-stream":
		return false
	case score(source) != score(wasSource):
		return score(source) > score(wasSource)
	}
	return strings.HasPrefix(was, "application/") && !strings.HasPrefix(t, "application/")
}

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "usage: gen <db.json> <version> <out.go>")
		os.Exit(2)
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var db map[string]entry
	if err := json.Unmarshal(raw, &db); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	types := make([]string, 0, len(db))
	for t := range db {
		types = append(types, t)
	}
	sort.Strings(types)
	byExt := map[string]string{}
	compressible := map[string]bool{}
	for _, t := range types {
		e := db[t]
		if e.Compressible != nil {
			compressible[t] = *e.Compressible
		}
		for _, ext := range e.Extensions {
			if was, ok := byExt[ext]; ok && !better(t, e.Source, was, db[was].Source) {
				continue
			}
			byExt[ext] = t
		}
	}
	exts := make([]string, 0, len(byExt))
	for ext := range byExt {
		exts = append(exts, ext)
	}
	sort.Strings(exts)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen from mime-db %s (MIT, https://github.com/jshttp/mime-db); DO NOT EDIT.\n\npackage mimetypes\n\n", os.Args[2])
	b.WriteString("var byExtension = map[string]string{\n")
	for _, ext := range exts {
		fmt.Fprintf(&b, "\t%q: %q,\n", ext, byExt[ext])
	}
	b.WriteString("}\n\nvar compressible = map[string]bool{\n")
	for _, t := range types {
		if c, ok := compressible[t]; ok {
			fmt.Fprintf(&b, "\t%q: %v,\n", t, c)
		}
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(os.Args[3], out, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// gen writes files_gen.go from the sibling templates folder. Run with `go generate` in the
// templates package. Files ignored by the templates' own .gitignore rules and build output are
// left out, so the embedded copy is what a fresh clone holds.
package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/whisk-run/cli/templates/source"
)

func main() {
	root := "../../templates"
	if len(os.Args) > 1 {
		root = os.Args[1]
	}
	var b strings.Builder
	b.WriteString("// Code generated by go generate from ../../templates; DO NOT EDIT.\n\npackage templates\n\nvar files = map[string]map[string]File{\n")
	for _, name := range []string{"typescript", "python", "go", "shop"} {
		set, err := source.Read(filepath.Join(root, name))
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		paths := make([]string, 0, len(set))
		for p := range set {
			paths = append(paths, p)
		}
		sort.Strings(paths)
		fmt.Fprintf(&b, "\t%q: {\n", name)
		for _, p := range paths {
			f := set[p]
			fmt.Fprintf(&b, "\t\t%q: {Mode: %#o, Content: %q},\n", p, uint32(f.Mode), f.Content)
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		fmt.Fprintln(os.Stderr, "generated source does not format:", err)
		os.Exit(1)
	}
	if err := os.WriteFile("files_gen.go", src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
